#!/usr/bin/env python3
"""Generate a REPRESENTATIVE BTS (cell-site) layer for the console.

These are illustrative infrastructure points — plausible tower positions,
operators and bands clustered around the cities and toll corridors that the
CCTV dataset covers. They are NOT a real tower registry and NOT tied to any
device location: the layer is map context (where cell coverage sits relative
to the road network), nothing more.

To use real data instead, replace the output with a tower export from an open
source such as OpenCelliD (opencellid.org), keeping the same record shape:
  {id, operator, band, g, city, lat, lng, radius}

Usage:
    python3 tools/gen_bts.py                # ~550 sites from cctv-data.js
    python3 tools/gen_bts.py --per-city 40  # density knob
"""
import argparse
import collections
import json
import math
import pathlib
import random

ROOT = pathlib.Path(__file__).resolve().parent.parent
CCTV = ROOT / "js" / "cctv-data.js"
OUT = ROOT / "js" / "bts-data.js"

# Indonesian mobile operators with rough market weighting + the bands each runs.
OPERATORS = [
    ("Telkomsel", 0.33, [("900", "4G"), ("1800", "4G"), ("2100", "4G"), ("2300", "5G")]),
    ("Indosat",   0.23, [("900", "4G"), ("1800", "4G"), ("2100", "4G"), ("2100", "5G")]),
    ("XL Axiata", 0.20, [("900", "4G"), ("1800", "4G"), ("2100", "4G"), ("2300", "5G")]),
    ("Tri",       0.14, [("1800", "4G"), ("2100", "4G")]),
    ("Smartfren", 0.10, [("850", "4G"), ("2300", "4G"), ("2300", "5G")]),
]
# Denser metros get smaller cells; open toll corridors get bigger ones.
URBAN = {"Jakarta", "Bandung", "Surabaya", "Medan", "Semarang", "Makassar",
         "Bekasi", "Tangerang", "Depok", "Bogor"}

M_PER_DEG = 111_320.0


def load_cams():
    src = CCTV.read_text(encoding="utf-8")
    marker = "window.CCTV_CAMERAS = "
    return json.loads(src[src.index(marker) + len(marker):].rstrip().rstrip(";"))


def pick_operator(rng):
    r, acc = rng.random(), 0.0
    for name, w, bands in OPERATORS:
        acc += w
        if r <= acc:
            return name, bands
    return OPERATORS[0][0], OPERATORS[0][2]


def jitter(lat, lng, meters, rng):
    ang = rng.random() * 2 * math.pi
    d = abs(rng.gauss(0, meters))
    dlat = (d * math.cos(ang)) / M_PER_DEG
    dlng = (d * math.sin(ang)) / (M_PER_DEG * math.cos(math.radians(lat)))
    return round(lat + dlat, 6), round(lng + dlng, 6)


def build(cams, per_city, cap, seed=42):
    rng = random.Random(seed)
    by_place = collections.defaultdict(list)
    for c in cams:
        by_place[c["city"]].append(c)

    sites, sid = [], 1
    for place, group in by_place.items():
        urban = place in URBAN
        spread = 2600 if urban else 9000           # metres around a seed camera
        # density scales with how many cameras (≈ how much road/urban area) are here
        n = max(6, min(per_city, int(per_city * len(group) / 18) + 6))
        for _ in range(n):
            seed_cam = rng.choice(group)
            lat, lng = jitter(seed_cam["lat"], seed_cam["lng"], spread, rng)
            op, bands = pick_operator(rng)
            band, g = rng.choice(bands)
            radius = rng.randint(350, 900) if urban else rng.randint(1200, 3000)
            sites.append({
                "id": f"BTS-{sid:04d}",
                "operator": op,
                "band": band,
                "g": g,
                "city": place,
                "lat": lat,
                "lng": lng,
                "radius": radius,
            })
            sid += 1

    rng.shuffle(sites)
    sites = sites[:cap]
    sites.sort(key=lambda s: (s["city"], s["operator"]))
    return sites


def write(sites):
    by_op = collections.Counter(s["operator"] for s in sites)
    g5 = sum(1 for s in sites if s["g"] == "5G")
    meta = {
        "note": ("Representative cell-site layer — illustrative infrastructure positions, "
                 "NOT a real tower registry and NOT linked to device location. "
                 "Swap in OpenCelliD data via tools/gen_bts.py for real coordinates."),
        "count": len(sites),
        "operators": dict(by_op),
        "fiveG": g5,
    }
    rows = ",\n".join("  " + json.dumps(s, ensure_ascii=False, separators=(",", ":")) for s in sites)
    OUT.write_text(
        "/* AUTO-GENERATED by tools/gen_bts.py — do not edit by hand.\n"
        " *\n"
        " * REPRESENTATIVE cell-site (BTS) layer: illustrative infrastructure points\n"
        " * clustered around the CCTV cities/corridors. NOT a real tower registry and\n"
        " * NOT tied to device location — map context only. See tools/gen_bts.py to\n"
        " * swap in real OpenCelliD data.\n"
        " */\n"
        f"window.BTS_SOURCE = {json.dumps(meta, ensure_ascii=False)};\n\n"
        f"window.BTS_SITES = [\n{rows}\n];\n",
        encoding="utf-8",
    )
    return meta


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--per-city", type=int, default=40, help="target sites per place (default 40)")
    ap.add_argument("--cap", type=int, default=560, help="hard cap on total sites (default 560)")
    args = ap.parse_args()

    sites = build(load_cams(), args.per_city, args.cap)
    meta = write(sites)
    print(f"wrote {OUT.relative_to(ROOT)}: {meta['count']} representative cell-sites "
          f"({meta['fiveG']} 5G)")
    for op, n in collections.Counter(s["operator"] for s in sites).most_common():
        print(f"  {n:4d}  {op}")


if __name__ == "__main__":
    main()
